"""
Recovery Plan and Recovery Plan Action SQLAlchemy ORM models for UNDOX.
Defines persistent recovery plans generated by the Failure Recovery Planning Engine.
Preserves original execution history by keeping recovery plans in distinct tables.
"""

import enum
import uuid
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Any, Dict, List, Optional

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from backend.app.database import Base

if TYPE_CHECKING:
    from backend.app.models.audit import AuditEvent
    from backend.app.models.execution import ExecutionStep, WorkflowExecution
    from backend.app.models.workflow import WorkflowInstance


class RecoveryPlanStatus(str, enum.Enum):
    """
    Allowed lifecycle states for a RecoveryPlan.
    - DRAFT: Plan is being composed.
    - GENERATED: Plan has been generated and is awaiting review or execution.
    - PENDING: Plan is queued awaiting review or execution approval.
    - APPROVED: Plan has been reviewed and approved by an operator.
    - REJECTED: Plan was reviewed and rejected.
    - EXECUTING: Recovery actions are actively being applied.
    - COMPLETED: All recovery actions finished successfully.
    - FAILED: Recovery execution failed.
    """
    DRAFT = "DRAFT"
    GENERATED = "GENERATED"
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    EXECUTING = "EXECUTING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"


class RecoveryActionType(str, enum.Enum):
    """
    Allowed action categories within a RecoveryPlan.
    - COMPENSATE: Undo or reverse the side effects of a completed step.
    - RETRY: Re-attempt execution of a failed step.
    - SKIP: Intentionally bypass an unexecuted or non-critical step.
    - MANUAL_REVIEW: Mark step as requiring human evaluation before proceeding.
    """
    COMPENSATE = "COMPENSATE"
    RETRY = "RETRY"
    SKIP = "SKIP"
    MANUAL_REVIEW = "MANUAL_REVIEW"


class RecoveryActionStatus(str, enum.Enum):
    """
    Allowed state for an individual recovery plan action.
    - PROPOSED: Action is planned and ready for approval/execution.
    - REQUIRES_MANUAL_REVIEW: Action is unsafe or unsupported for automatic execution.
    - EXECUTING: Action is actively being executed.
    - COMPLETED: Action finished successfully.
    - FAILED: Action execution encountered an error.
    - SKIPPED: Action was bypassed (e.g. following a prior action failure).
    """
    PROPOSED = "PROPOSED"
    REQUIRES_MANUAL_REVIEW = "REQUIRES_MANUAL_REVIEW"
    EXECUTING = "EXECUTING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"


class RecoveryPlan(Base):
    """
    Represents a proposed recovery plan for an existing failed WorkflowExecution.
    Decoupled from execution records to strictly preserve original execution history.
    """
    __tablename__ = "recovery_plans"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    execution_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("workflow_executions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    workflow_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("workflow_instances.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    status: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        default=RecoveryPlanStatus.GENERATED.value,
        index=True,
    )
    strategy: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
    )
    summary: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    requires_manual_approval: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    execution: Mapped["WorkflowExecution"] = relationship(
        back_populates="recovery_plans",
    )
    workflow: Mapped["WorkflowInstance"] = relationship()
    actions: Mapped[List["RecoveryPlanAction"]] = relationship(
        back_populates="plan",
        cascade="all, delete-orphan",
        order_by="RecoveryPlanAction.action_order",
    )
    audit_events: Mapped[List["AuditEvent"]] = relationship(
        "AuditEvent",
        back_populates="recovery_plan",
        order_by="AuditEvent.timestamp.asc()",
        foreign_keys="AuditEvent.recovery_plan_id",
    )

    @property
    def decision_reason(self) -> Optional[str]:
        """Extracts operator decision reason from summary audit trail."""
        if "--- Operator Decision ---" in (self.summary or ""):
            for line in self.summary.splitlines():
                if line.startswith("Reason:"):
                    return line.split("Reason:", 1)[1].strip()
        return getattr(self, "_decision_reason", None)

    @property
    def decision_operator(self) -> Optional[str]:
        """Extracts operator identifier from summary audit trail."""
        if "--- Operator Decision ---" in (self.summary or ""):
            for line in self.summary.splitlines():
                if line.startswith("Operator:"):
                    return line.split("Operator:", 1)[1].strip()
        return getattr(self, "_decision_operator", None)

    @property
    def decided_at(self) -> Optional[datetime]:
        """Extracts operator decision timestamp from summary audit trail."""
        if "--- Operator Decision ---" in (self.summary or ""):
            for line in self.summary.splitlines():
                if line.startswith("Timestamp:"):
                    raw = line.split("Timestamp:", 1)[1].strip()
                    try:
                        return datetime.fromisoformat(raw)
                    except ValueError:
                        return None
        return getattr(self, "_decided_at", None)

    def __repr__(self) -> str:
        return (
            f"<RecoveryPlan(id={self.id}, execution_id={self.execution_id}, "
            f"strategy='{self.strategy}', status='{self.status}')>"
        )


class RecoveryPlanAction(Base):
    """
    Represents an individual planned recovery action within a RecoveryPlan.
    Specifies exact target step, compensation logic or retry, and manual review requirements.
    """
    __tablename__ = "recovery_plan_actions"

    __table_args__ = (
        UniqueConstraint("plan_id", "action_order", name="uq_recovery_plan_action_order"),
        CheckConstraint("action_order > 0", name="ck_recovery_plan_action_order_positive"),
        CheckConstraint("target_step_order > 0", name="ck_recovery_plan_target_step_order_positive"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    plan_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("recovery_plans.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    action_order: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )
    target_step_order: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )
    target_execution_step_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("execution_steps.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    action_type: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
    )
    target_step_name: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
    )
    status: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        default=RecoveryActionStatus.PROPOSED.value,
    )
    is_reversible: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
    )
    explanation: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    compensation_details: Mapped[Optional[Dict[str, Any]]] = mapped_column(
        JSONB,
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
        nullable=False,
    )

    # Relationship to parent plan
    plan: Mapped["RecoveryPlan"] = relationship(
        back_populates="actions",
    )
    # Optional reference to original execution step
    target_execution_step: Mapped[Optional["ExecutionStep"]] = relationship()

    def __repr__(self) -> str:
        return (
            f"<RecoveryPlanAction(id={self.id}, plan_id={self.plan_id}, "
            f"order={self.action_order}, type='{self.action_type}', status='{self.status}')>"
        )
